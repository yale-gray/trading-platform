"""Shared Hypothesis strategies (SPEC-005 section 4, T13).

``valid_bar`` / ``bar_paths`` build valid OHLC bars (low <= min(o, c) <= max(o, c) <= high,
price in [0.01, 1e5]). ``scenarios`` builds a whole engine run: bars per date (equities skip
weekends, bars go missing, ``vol20``/``atr14`` blink out, a crash regime can be forced), target
weights per sleeve per bar, kill-switch resets and save/restore points.

The path itself is generated by a ``random.Random`` seeded from a drawn integer, with the
shape knobs drawn by Hypothesis; this keeps examples small (hundreds of floats per run
would trip Hypothesis' size health checks) while the knobs still shrink.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal

from hypothesis import strategies as st

from tradebot.sim.broker import Bar

EQUITIES = ("SPY", "QQQ", "IEF")
CRYPTOS = ("BTC/USD", "ETH/USD")
SLEEVE_POOLS: dict[str, tuple[str, ...]] = {
    "core_momentum": EQUITIES,
    "mean_reversion": EQUITIES,
    "crypto_trend": CRYPTOS,
}


@st.composite
def valid_bar(draw: st.DrawFn, symbol: str = "SPY") -> Bar:
    """One valid OHLC bar with prices in [0.01, 1e5] at 2-4 dp."""
    dp = draw(st.integers(2, 4))
    q = 10**dp

    def px() -> float:
        return draw(st.integers(max(1, int(0.01 * q)), 10**5 * q)) / q

    o, c = px(), px()
    hi = max(o, c) * (1 + draw(st.integers(0, 300)) / 10000)
    lo = min(o, c) * (1 - draw(st.integers(0, 300)) / 10000)
    return Bar(
        symbol=symbol, open=o, high=round(hi, dp + 2), low=max(round(lo, dp + 2), 0.01), close=c
    )


@dataclass(frozen=True)
class Step:
    """One engine bar plus what the harness does after it."""

    asof: date
    bars: dict[str, Bar]
    targets: dict[str, dict[str, float]]  # sleeve -> weights submitted after the bar
    restore: bool = False  # save/restore the engine after this bar's submissions
    reset_kill: bool = False  # operator reset attempt after this bar


@dataclass(frozen=True)
class Scenario:
    """A full engine run."""

    kill_threshold: Decimal
    stop_mult: Decimal
    ambient_prec: int
    steps: tuple[Step, ...]


def _make_steps(
    rnd: random.Random,
    n_bars: int,
    start: date,
    crash_at: int,
    crash_len: int,
    crash_depth: float,
    vol: float,
    p_missing: float,
    p_target: float,
    restore_every: int,
    p_reset: float,
) -> tuple[Step, ...]:
    syms = EQUITIES + CRYPTOS
    px = {s: 10 ** rnd.uniform(0.7, 4.6) for s in syms}  # ~5 .. 40000
    seen: set[str] = set()
    steps: list[Step] = []
    d = start
    for t in range(n_bars):
        d += timedelta(days=1)
        bars: dict[str, Bar] = {}
        for s in syms:
            if s in EQUITIES and d.weekday() >= 5:
                continue
            if rnd.random() < p_missing:
                continue
            o = px[s] * (1 + rnd.gauss(0, vol / 2))
            c = o * (1 + rnd.gauss(0, vol))
            if crash_at <= t < crash_at + crash_len:
                c = o * (1 - rnd.random() * crash_depth)
            o, c = max(o, 0.05), max(c, 0.05)
            px[s] = c
            atr = c * rnd.uniform(0.005, 0.05) if rnd.random() > 0.05 else None
            v20 = rnd.uniform(0.003, 0.05) if rnd.random() > 0.05 else None
            bars[s] = Bar(
                symbol=s,
                open=o,
                high=max(o, c) * 1.002,
                low=min(o, c) * 0.998,
                close=c,
                vol20=v20,
                atr14=atr,
            )
        if not bars:
            continue
        seen |= set(bars)
        targets: dict[str, dict[str, float]] = {}
        for sid, pool in SLEEVE_POOLS.items():
            if rnd.random() >= p_target:
                continue
            avail = [s for s in pool if s in seen]
            k = rnd.randint(0, len(avail))
            chosen = rnd.sample(avail, k)
            targets[sid] = {s: rnd.choice((rnd.uniform(0.0, 1.0 / k), 1e-9, 0.0)) for s in chosen}
        steps.append(
            Step(
                asof=d,
                bars=bars,
                targets=targets,
                restore=restore_every > 0 and t % restore_every == 0,
                reset_kill=rnd.random() < p_reset,
            )
        )
    return tuple(steps)


@st.composite
def scenarios(
    draw: st.DrawFn,
    min_bars: int = 25,
    max_bars: int = 80,
    with_restores: bool = True,
) -> Scenario:
    """Random engine run: bar path, target weights, crash, resets, restore points."""
    n_bars = draw(st.integers(min_bars, max_bars))
    seed = draw(st.integers(0, 2**31 - 1))
    crash = draw(st.booleans())
    start = date(2024, 1, 1) + timedelta(days=draw(st.integers(0, 400)))
    steps = _make_steps(
        random.Random(seed),
        n_bars,
        start,
        crash_at=draw(st.integers(8, max(9, n_bars - 8))) if crash else n_bars + 1,
        crash_len=draw(st.integers(3, 12)),
        crash_depth=draw(st.sampled_from((0.05, 0.12, 0.25, 0.4))),
        vol=draw(st.sampled_from((0.005, 0.015, 0.04))),
        p_missing=draw(st.sampled_from((0.0, 0.03, 0.2))),
        p_target=draw(st.sampled_from((0.1, 0.4, 0.8))),
        restore_every=draw(st.integers(3, 11)) if with_restores else 0,
        p_reset=draw(st.sampled_from((0.0, 0.05, 0.3))),
    )
    return Scenario(
        kill_threshold=draw(st.sampled_from((Decimal("0.20"), Decimal("0.10")))),
        stop_mult=draw(st.sampled_from((Decimal("1.5"), Decimal("2.5")))),
        ambient_prec=draw(st.sampled_from((5, 28, 60))),
        steps=steps,
    )


@st.composite
def order_plan(draw: st.DrawFn, symbols: tuple[str, ...] = EQUITIES) -> dict[str, float]:
    """One sleeve's target weights: some zero, some tiny, sum <= 1."""
    k = draw(st.integers(0, len(symbols)))
    chosen = draw(st.permutations(symbols))[:k]
    out: dict[str, float] = {}
    for s in chosen:
        out[s] = draw(
            st.one_of(
                st.just(0.0),
                st.just(1e-9),
                st.floats(min_value=0.0, max_value=1.0 / max(k, 1), allow_nan=False),
            )
        )
    return out
